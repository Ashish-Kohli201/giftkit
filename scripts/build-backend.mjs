// Builds the Apps Script project: backend/dist/Code.gs (one file to paste, or push with clasp) and backend/dist/appsscript.json.
//
//   npm run build:backend
//
// The bundle is, in order: the shared rules from core/ (so the browser and the backend can never disagree about a price or a payment),
// the product manifests (so the backend knows every option and price), then backend/src/*.js. Apps Script has no ES modules, so the
// shared files have their `import` lines and `export` keywords removed here; nothing else is changed.
import { readFile, readdir, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const read = (p) => readFile(join(ROOT, p), 'utf8').then((t) => t.replace(/\r\n/g, '\n'));

/** Turn an ES module into plain script text: drop imports, drop the word `export`. */
const plain = (source) => source
  .replace(/^import\s[^;]*;\n/gm, '')
  .replace(/^export default\s+/gm, 'var _default = ')
  .replace(/^export\s+(?=(const|let|var|function|async function|class)\b)/gm, '');

const banner = (title) => `\n// ${'='.repeat(100)}\n// ${title}\n// ${'='.repeat(100)}\n`;

export async function buildBackend() {
  const ids = JSON.parse(await read('products/index.json'));
  const products = {};
  for (const id of ids) {
    const m = JSON.parse(await read(`products/${id}/product.json`));
    // the backend needs what it checks and prices; the storefront-only copy (shop, sample) stays out
    products[id] = { id: m.id, name: m.name, skins: m.skins, price: m.price, options: m.options };
  }

  const parts = [
    '// GENERATED by `npm run build:backend` from core/, products/ and backend/src/. Do not edit this file: edit the sources and rebuild.',
    '// The only thing to edit in the Apps Script editor is `settings_()` (the 00-settings section below).',
    banner('shared rules (core/contract.js, core/options.js, core/payments/upi.js)'),
    plain(await read('core/contract.js')),
    plain(await read('core/options.js')),
    plain(await read('core/payments/upi.js')),
    banner('products (products/*/product.json)'),
    `const PRODUCTS = ${JSON.stringify(products, null, 2)};\n`,
  ];
  const files = (await readdir(join(ROOT, 'backend/src'))).filter((f) => f.endsWith('.js')).sort();
  for (const f of files) parts.push(banner(`backend/src/${f}`), await read(`backend/src/${f}`));

  const code = `${parts.join('\n')}\n`;
  const manifest = await read('backend/appsscript.json');
  return { code, manifest };
}

/**
 * The same bundle with YOUR settings filled in, ready to paste into the Apps Script editor (backend/dist/Code.paste.gs, not committed).
 * Values come from a JSON file such as backend/my-settings.json (not committed either).
 */
export function withSettings(code, settings) {
  const start = code.indexOf('function settings_() {');
  const end = code.indexOf('\n}\n', start) + 3;
  if (start < 0 || end < 3) throw new Error('settings_() not found in the bundle');
  const original = new Function(`${code.slice(start, end)}; return settings_();`)();
  const merged = { ...original, ...settings };
  const lines = Object.entries(merged).map(([k, v]) => `    ${k}: ${JSON.stringify(String(v))},`);
  return `${code.slice(0, start)}function settings_() {\n  return {\n${lines.join('\n')}\n  };\n}\n${code.slice(end)}`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { code, manifest } = await buildBackend();
  await mkdir(join(ROOT, 'backend/dist'), { recursive: true });
  await writeFile(join(ROOT, 'backend/dist/Code.gs'), code);
  await writeFile(join(ROOT, 'backend/dist/appsscript.json'), manifest);
  console.log(`backend/dist/Code.gs  ${code.split('\n').length} lines`);
  const at = process.argv.indexOf('--settings');
  if (at > 0) {
    const mine = JSON.parse(await readFile(join(ROOT, process.argv[at + 1]), 'utf8'));
    await writeFile(join(ROOT, 'backend/dist/Code.paste.gs'), withSettings(code, mine));
    console.log('backend/dist/Code.paste.gs  (your settings filled in: paste THIS one, and never commit it)');
  }
}
